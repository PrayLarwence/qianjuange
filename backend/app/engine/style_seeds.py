def seed_builtin_styles(db: Session) -> int:
    """upsert 所有内置风格。返回新增/更新的总条数。"""
    count = 0
    for spec in BUILTIN_PROFILES:
        existing = db.query(StyleProfile).filter_by(id=spec["id"]).first()
        if existing is None:
            db.add(StyleProfile(
                id=spec["id"],
                name=spec["name"],
                kind="builtin",
                category=spec["category"],
                description=spec["description"],
                spec_text=spec["spec_text"],
                sample_paragraphs=spec["sample_paragraphs"],
                frozen=1,  # builtin 默认锁定，用户要改请复制为 custom
                created_at=datetime.utcnow(),
                updated_at=datetime.utcnow(),
            ))
        else:
            # 让我们能改 spec 而不丢用户已绑定的 World.style_profile_id 关系
            existing.name = spec["name"]
            existing.category = spec["category"]
            existing.description = spec["description"]
            existing.spec_text = spec["spec_text"]
            existing.sample_paragraphs = spec["sample_paragraphs"]
            existing.frozen = 1
            existing.updated_at = datetime.utcnow()
        count += 1
    db.commit()
    return count
